# Updates the bundled libVLC of Windows in Libs/vlc: headers, x64 and x86 libraries and the plugins listed in
# Libs/vlc/plugins.txt. The release packages have no SDK, so the headers come from the source package and the import
# libraries are generated from the exports of the libraries.

param([string]$Version = "3.0.23")

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$rootDir = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot "..\.."))
$vlcDir = Join-Path $rootDir "Libs\vlc"
$workDir = Join-Path ([IO.Path]::GetTempPath()) "ten-vlc-windows"
$baseUrl = "https://download.videolan.org/pub/videolan/vlc/$Version"

$vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
$vsDir = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
$toolsVersion = (Get-Content (Join-Path $vsDir "VC\Auxiliary\Build\Microsoft.VCToolsVersion.default.txt")).Trim()
$toolsDir = Join-Path $vsDir "VC\Tools\MSVC\$toolsVersion\bin\Hostx64"

New-Item -ItemType Directory -Force -Path $workDir | Out-Null

function Get-Package([string]$url, [string]$name)
{
    $path = Join-Path $workDir $name
    if (-not (Test-Path $path))
    {
        Write-Host "Downloading $url"
        Invoke-WebRequest -Uri $url -OutFile $path
    }

    return $path
}

# Headers: libvlc_version.h is generated by the VLC build from its template.
$sourcePackage = Get-Package "$baseUrl/vlc-$Version.tar.xz" "vlc-$Version.tar.xz"
& "$env:SystemRoot\System32\tar.exe" -xJf $sourcePackage -C $workDir "vlc-$Version/include/vlc"
$sourceIncludeDir = Join-Path $workDir "vlc-$Version\include\vlc"
$versionParts = $Version.Split(".")
$template = Get-Content (Join-Path $sourceIncludeDir "libvlc_version.h.in") -Raw
$template = $template.Replace("@VERSION_MAJOR@", $versionParts[0]).Replace("@VERSION_MINOR@", $versionParts[1])
$template = $template.Replace("@VERSION_REVISION@", $versionParts[2]).Replace("@VERSION_EXTRA@", "0")
Set-Content -Path (Join-Path $sourceIncludeDir "libvlc_version.h") -Value $template -NoNewline

$includeDir = Join-Path $vlcDir "include\vlc"
Remove-Item -Recurse -Force $includeDir -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $includeDir | Out-Null
Copy-Item (Join-Path $sourceIncludeDir "*.h") $includeDir

$plugins = Get-Content (Join-Path $vlcDir "plugins.txt") | Where-Object { $_ -and -not $_.StartsWith("#") }

foreach ($target in @(@{ Name = "win64"; Platform = "x64" }, @{ Name = "win32"; Platform = "x86" }))
{
    $package = Get-Package "$baseUrl/$($target.Name)/vlc-$Version-$($target.Name).zip" "vlc-$Version-$($target.Name).zip"
    $extractDir = Join-Path $workDir $target.Name
    Remove-Item -Recurse -Force $extractDir -ErrorAction SilentlyContinue
    Expand-Archive -Path $package -DestinationPath $extractDir
    $packageDir = Join-Path $extractDir "vlc-$Version"

    $platformDir = Join-Path $vlcDir $target.Platform
    Remove-Item -Recurse -Force $platformDir -ErrorAction SilentlyContinue
    New-Item -ItemType Directory -Force -Path $platformDir | Out-Null

    foreach ($library in @("libvlc", "libvlccore"))
    {
        $dllPath = Join-Path $packageDir "$library.dll"
        Copy-Item $dllPath $platformDir

        # Import library from the exported names, which are undecorated C functions.
        $exports = & (Join-Path $toolsDir "x64\dumpbin.exe") -nologo -exports $dllPath
        $isTable = $false
        $definition = @("LIBRARY $library", "EXPORTS")
        foreach ($line in $exports)
        {
            if ($line -match "ordinal\s+hint\s+RVA")
            {
                $isTable = $true
                continue
            }

            if ($isTable -and $line -match "^\s+\d+\s+[0-9A-F]+\s+[0-9A-F]+\s+(\S+)")
            {
                $definition += "    " + $Matches[1]
            }
        }

        $definitionPath = Join-Path $workDir "$library-$($target.Platform).def"
        Set-Content -Path $definitionPath -Value $definition
        & (Join-Path $toolsDir "$($target.Platform)\lib.exe") -nologo "-def:$definitionPath" "-machine:$($target.Platform)" "-out:$(Join-Path $platformDir "$library.lib")" | Out-Null
        Remove-Item (Join-Path $platformDir "$library.exp")
    }

    foreach ($plugin in $plugins)
    {
        $source = Join-Path $packageDir "plugins\$plugin.dll"
        $destination = Join-Path $platformDir "plugins\$plugin.dll"
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
        Copy-Item $source $destination
    }

    Write-Host "libVLC $Version for $($target.Platform): $($plugins.Count) plugins."
}
